static Bytes read_raw(const fs::path &p,size_t size){
    require(fs::is_regular_file(p)&&fs::file_size(p)==size,"missing or incorrect RAW size");
    Bytes b(size);std::ifstream f(p,std::ios::binary);
    require(bool(f.read(reinterpret_cast<char*>(b.data()),(std::streamsize)size)),"read RAW failed");
    return b;
}
static void write_raw(const fs::path &p,const Bytes &b){
    std::ofstream f(p,std::ios::binary|std::ios::trunc);
    require(bool(f.write(reinterpret_cast<const char*>(b.data()),(std::streamsize)b.size())),"write RAW failed");
}
